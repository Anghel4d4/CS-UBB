function s = Sinus(x)
        if abs(x) < 10^-8
            s = x;
        elseif abs(x) > pi/6
            u = x/3;
            sinu = u .* (-479249/11511339840 * u.^6 + 34911/7613320 * u.^4 - 29593/207636 * u.^2 + 1) / (1 + 1671/69212 * u.^2 + 97/351384 * u.^4 + 2623/1644477120 * u.^6);
            s = (3 - 4 * sinu^2) * sinu;
        elseif abs(x) <= pi/6
            u = x;
            sinu = u .* (-479249/11511339840 * u.^6 + 34911/7613320 * u.^4 - 29593/207636 * u.^2 + 1) / (1 + 1671/69212 * u.^2 + 97/351384 * u.^4 + 2623/1644477120 * u.^6);
            s = sinu; 
        end
end