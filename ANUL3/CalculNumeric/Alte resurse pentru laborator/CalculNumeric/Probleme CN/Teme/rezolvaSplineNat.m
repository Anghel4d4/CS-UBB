function a = rezolvaSplineNat(x,y)
    n = length(x);
    A = zeros(3*n-3);
    b = zeros(3*n-3,1);
    A(1,2) = 1;
    b(1) = 0;
    for i=1:n-2
        A(3*i-1,3*i-2)=(x(i+1)-x(i))^3;
        A(3*i-1,3*i-1)=(x(i+1)-x(i))^2;
        A(3*i-1,3*i)=(x(i+1)-x(i));
        b(3*i-1)=y(i+1)-y(i);
        A(3*i,3*i-2)=3*(x(i+1)-x(i))^2;
        A(3*i,3*i-1)=2*(x(i+1)-x(i));
        A(3*i,3*i)=1;
        A(3*i,3*i+3)=-1;
        b(3*i)=0;
        A(3*i+1,3*i-2)=6*(x(i+1)-x(i));
        A(3*i+1,3*i-1)=2;
        A(3*i+1,3*i+2)=-2;
        b(3*i+1)=0;
    end
    A(3*n-4,3*n-5)=(x(n)-x(n-1))^3;
    A(3*n-4,3*n-4)=(x(n)-x(n-1))^2;
    A(3*n-4,3*n-3)=(x(n)-x(n-1));
    b(3*n-4)=y(n)-y(n-1);
    A(3*n-3,3*n-5)=6*(x(n)-x(n-1));
    A(3*n-3,3*n-4)=2;
    b(3*n-3)=0;
    a=(A\b)';