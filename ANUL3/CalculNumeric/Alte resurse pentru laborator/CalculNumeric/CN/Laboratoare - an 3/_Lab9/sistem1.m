function a=sistem1(x,y)
n=length(x)-1;
M=zeros(4*n);
N=zeros(4*n,1);

M(1,1) = x(1)^3;
M(1,2)= x(1)^2;
M(1,3)=x(1);
M(1,4) = 1;
N(1)=y(1);

M(2,1)=6*x(1);
M(2,2) = 2;
N(2)=0;
for i=1:n-1

    M(4*i-1, 4*i-3)=x(i+1)^3;
    M(4*i-1, 4*i-2)=x(i+1)^2;
    M(4*i-1, 4*i-1)=x(i+1);
    M(4*i-1, 4*i)=1;
    N(4*i-1)=y(i+1);
	
    M(4*i, 4*i-3)=3*x(i+1)^2;
    M(4*i, 4*i-2)=2*x(i+1);
    M(4*i, 4*i-1)=1;
    M(4*i, 4*i+1)=-3*x(i+1)^2;
    M(4*i, 4*i+2)=-2*x(i+1);
    M(4*i, 4*i+3)=-1;
    N(4*i)=0;
	
    M(4*i+1, 4*i-3)=6*x(i+1);
    M(4*i+1, 4*i-2)=2;
    M(4*i+1, 4*i+1)=-6*x(i+1);
    M(4*i+1, 4*i+2)=2;
    N(4*i+1)=0;
	
    M(4*i+2,4*i+1)=x(i+1)^3;
    M(4*i+2, 4*i+2)=x(i+1)^2;
    M(4*i+2, 4*i+3)=x(i+1);
    M(4*i+2, 4*i+4)=1;
    N(4*i+2)=y(i+1);
end

M(4*n-1,4*n-3)=6*x(n-1);
M(4*n-1,4*n-2)=2;
N(4*n-1) = 0;

M(4*n,4*n-3) = x(n+1)^3;
M(4*n,4*n-2)=x(n+1)^2;
M(4*n, 4*n-1)=x(n+1);
M(4*n,4*n) = 1;
N(4*n) = y(n+1);
a=M\N;


